/**
 * The tray icon (the menu bar icon on macOS) that keeps the app reachable while its window is hidden: a click opens
 * it, and the menu mutes, deafens, sets the status or quits for real. The renderer reports
 * what to show (setTrayState) and runs what the menu asks (the onCommand callback).
 */

import { readFileSync } from 'node:fs'

import { Menu, nativeImage, Tray, type MenuItemConstructorOptions, type NativeImage } from 'electron'

import tray16 from '../../resources/tray-16.png?asset'
import tray20 from '../../resources/tray-20.png?asset'
import tray24 from '../../resources/tray-24.png?asset'
import tray32 from '../../resources/tray-32.png?asset'
import trayTemplate from '../../resources/trayTemplate.png?asset'
import trayTemplate2x from '../../resources/trayTemplate@2x.png?asset'

import type { TrayCommand, TrayState, TrayStatus } from '../shared/types'
import { t } from './i18n'

const STATUSES: readonly TrayStatus[] = ['online', 'idle', 'dnd', 'invisible']

let tray: Tray | null = null
let state: TrayState = { signedIn: false, muted: false, deafened: false, status: 'online' }
let handlers: { open(): void; quit(): void; command(cmd: TrayCommand): void } | null = null

/** The small logo (filled hexagon, the gold reads on light and dark taskbars), one bitmap per
 * display scale so Windows never resizes it. Generated by `npm run build:icons`. */
function icon(): NativeImage {
  if (process.platform === 'darwin') {
    // The menu bar: a template image (black + alpha) that macOS tints for light and dark bars.
    const image = nativeImage.createFromPath(trayTemplate)
    image.addRepresentation({ scaleFactor: 2, buffer: readFileSync(trayTemplate2x) })
    image.setTemplateImage(true)
    return image
  }
  const image = nativeImage.createFromPath(tray16)
  for (const [scaleFactor, path] of [[1.25, tray20], [1.5, tray24], [2, tray32]] as const) {
    image.addRepresentation({ scaleFactor, buffer: readFileSync(path) })
  }
  return image
}

function menu(): Menu {
  const items: MenuItemConstructorOptions[] = [{ label: t('system.tray.open'), click: () => handlers?.open() }]
  if (state.signedIn) {
    items.push(
      { type: 'separator' },
      { label: t('system.tray.mute'), type: 'checkbox', checked: state.muted, click: () => handlers?.command({ type: 'mute' }) },
      { label: t('system.tray.deafen'), type: 'checkbox', checked: state.deafened, click: () => handlers?.command({ type: 'deafen' }) },
      {
        label: t('system.tray.status'),
        submenu: STATUSES.map((value) => ({
          label: t(`system.status.${value}`),
          type: 'radio' as const,
          checked: state.status === value,
          click: () => handlers?.command({ type: 'status', status: value })
        }))
      }
    )
  }
  items.push({ type: 'separator' }, { label: t('system.tray.quit'), click: () => handlers?.quit() })
  return Menu.buildFromTemplate(items)
}

export function createTray(h: NonNullable<typeof handlers>): void {
  handlers = h
  tray = new Tray(icon())
  tray.setToolTip(t('system.tray.tooltip'))
  tray.setContextMenu(menu())
  tray.on('click', () => handlers?.open())
}

/** Rebuilds the menu (its texts follow the app's language). */
export function refreshTray(): void {
  tray?.setContextMenu(menu())
}

export function setTrayState(next: unknown): void {
  if (!next || typeof next !== 'object') throw new Error('Invalid tray state')
  const s = next as Partial<TrayState>
  state = {
    signedIn: s.signedIn === true,
    muted: s.muted === true,
    deafened: s.deafened === true,
    status: STATUSES.includes(s.status as TrayStatus) ? (s.status as TrayStatus) : 'online'
  }
  tray?.setContextMenu(menu())
}

/** A one-time hint next to the tray icon ("still running here"). */
export function notify(title: string, content: string): void {
  tray?.displayBalloon({ title, content, iconType: 'info' })
}

export function destroyTray(): void {
  tray?.destroy()
  tray = null
}
